"""Generate the proxy DLL sources from the real system DLL's export table.

Usage: python tools/gen_proxy.py [C:/Windows/System32/iphlpapi.dll]

Writes src/proxy.def, src/proxy_stubs.asm and src/proxy_names.inc. Every export of the real
library gets a stub that jumps through a pointer the DLL fills at load time, so anything in the
process that imports the library keeps working.

The live map loads as iphlpapi.dll: the server imports it, it is not a KnownDLL, and other
Enshrouded server mods already use powrprof.dll (Shared XP) and dinput8.dll (Quest Catch-Up).
"""
import pathlib
import site
import sys

sys.path.insert(0, site.getusersitepackages())
import pefile  # noqa: E402

src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else r"C:\Windows\System32\iphlpapi.dll")
out = pathlib.Path(__file__).resolve().parent.parent / "src"

pe = pefile.PE(str(src))
exports = sorted(
    ((s.ordinal, s.name.decode()) for s in pe.DIRECTORY_ENTRY_EXPORT.symbols if s.name),
    key=lambda e: e[0],
)
private = {"DllCanUnloadNow", "DllGetClassObject", "DllRegisterServer", "DllUnregisterServer"}

(out / "proxy.def").write_text(
    f"LIBRARY {src.stem.lower()}\nEXPORTS\n"
    + "".join(f"    {name}=lm_{name} @{ordinal}{' PRIVATE' if name in private else ''}\n"
              for ordinal, name in exports),
    encoding="ascii",
)

asm = [f"; Generated by tools/gen_proxy.py from {src.name}. Each stub jumps to the real export.",
       "EXTERN g_real_exports:QWORD", ".code"]
for index, (_, name) in enumerate(exports):
    asm += [f"lm_{name} PROC", f"    jmp qword ptr [g_real_exports + {index * 8}]", f"lm_{name} ENDP"]
asm.append("END")
(out / "proxy_stubs.asm").write_text("\n".join(asm) + "\n", encoding="ascii")

(out / "proxy_names.inc").write_text(
    f"// Generated by tools/gen_proxy.py from {src.name}, in stub order.\n"
    + "".join(f'"{name}",\n' for _, name in exports),
    encoding="ascii",
)
print(f"{len(exports)} exports from {src}")
