"""Writes src/items_generated.h: the runtime item ids of all "Material_*" items with their
debug names, from the unpacked server data (ItemRegistryResource: itemRefs[i] / dbgNames[i];
ItemInfo/<guid>_*.json: itemId.value, the 32-bit id the server uses at runtime).

Usage: python tools/extract_items.py --server <unpacked dir> --out src/items_generated.h
"""
import argparse
import glob
import json
import os


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--server", required=True)
    ap.add_argument("--out", default="src/items_generated.h")
    a = ap.parse_args()
    reg = json.load(open(glob.glob(os.path.join(a.server, "ItemRegistryResource", "*.json"))[0], encoding="utf-8"))
    rows = []
    for i, (guid, name) in enumerate(zip(reg["itemRefs"], reg["dbgNames"])):
        if not str(name).startswith("Material_"):
            continue
        files = glob.glob(os.path.join(a.server, "ItemInfo", f"{guid}_*.json"))
        if not files:
            continue
        info = json.load(open(files[0], encoding="utf-8"))
        item_id = (info.get("itemId") or {}).get("value")
        if item_id is None:
            continue
        rows.append((item_id, i, name))
    rows.sort()
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/extract_items.py from the server's item registry (build 25988414).\n")
        f.write("// {runtime item id, registry index, debug name} for every Material_* item.\n")
        f.write("struct ItemName { uint32_t id; uint32_t index; const char* name; };\n")
        f.write("constexpr ItemName kItemNames[] = {\n")
        for item_id, i, name in rows:
            f.write(f'    {{{item_id}u, {i}u, "{name}"}},\n')
        f.write("};\n")
    print(f"{len(rows)} material items written to {a.out}")


if __name__ == "__main__":
    main()
